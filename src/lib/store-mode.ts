/**
 * "Store-only mode": what a customer gets after opening a store's private
 * link (`/s/<slug>`, e.g. a QR code on a restaurant table). For a few hours
 * the browser stays inside that one store — the BODA logo, header and footer
 * lead back to it, and in-app navigation to anything else (other stores,
 * search, categories, the home page) is redirected to it by `src/proxy.ts`.
 *
 * It's a UX focus mode, not access control: the store page itself is public.
 * Opening a different BODA link from outside the app (typed URL, bookmark,
 * a link in another app) leaves the mode, so nobody gets stuck in it.
 *
 * Kept free of React/Next imports so the proxy and client code share it.
 */

/** Readable from JS on purpose: the header/footer render from it. */
export const STORE_MODE_COOKIE = "boda_store_mode";

/** Long enough for a meal or a shopping trip; the mode then lapses on its own. */
export const STORE_MODE_MAX_AGE_SECONDS = 6 * 60 * 60;

/** Store slugs are generated by `slugify(..., { strict: true })` (+ an optional nanoid suffix). */
export const STORE_SLUG_PATTERN = /^[a-z0-9_-]{1,120}$/i;

/** Paths a customer may visit in store mode besides the store itself. */
const SHARED_PREFIXES = [
  "/cart",
  "/checkout",
  "/auth",
  "/account",
  "/legal",
  // Role-gated dashboards (they bounce customers to `/`, which lands back on
  // the store) — kept reachable for a seller who opened their own link.
  "/seller",
  "/admin",
];

/** Leads to items from other stores, so it's off-limits in store mode. */
const BLOCKED_PREFIXES = ["/account/wishlist"];

function underPrefix(pathname: string, prefix: string) {
  return pathname === prefix || pathname.startsWith(`${prefix}/`);
}

export function isPathAllowedInStoreMode(pathname: string, slug: string): boolean {
  if (BLOCKED_PREFIXES.some((prefix) => underPrefix(pathname, prefix))) return false;
  if (underPrefix(pathname, `/stores/${slug}`)) return true;
  return SHARED_PREFIXES.some((prefix) => underPrefix(pathname, prefix));
}

/** The store slug from a `document.cookie`-style string, if store mode is on. */
export function readStoreModeSlug(cookieHeader: string): string | null {
  for (const part of cookieHeader.split(";")) {
    const [name, ...rest] = part.trim().split("=");
    if (name === STORE_MODE_COOKIE) {
      const value = decodeURIComponent(rest.join("="));
      return STORE_SLUG_PATTERN.test(value) ? value : null;
    }
  }
  return null;
}

/**
 * Runs in `<head>` before first paint: flags `<html data-store-mode>` so the
 * `store-mode:` CSS variant hides the marketplace chrome (search, nav,
 * marketplace footer) without a flash before React hydrates.
 */
export const STORE_MODE_BOOT_SCRIPT = `try{if(/(?:^|;\\s*)${STORE_MODE_COOKIE}=[^;]/.test(document.cookie))document.documentElement.setAttribute("data-store-mode","")}catch(e){}`;
